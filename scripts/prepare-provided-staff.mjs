// Builds an additive, repeatable seed for the user-approved fictional staff roster.
// This script only writes the SQL file; it never connects to a remote database.
import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const catalog = JSON.parse(await readFile(new URL("src/data/provided-catalog.json", root), "utf8"));
const roster = JSON.parse(await readFile(new URL("src/data/provided-staff.json", root), "utf8"));
const catalogKeys = new Set(catalog.businesses.map(shop => shop.source_key));
const seen = new Set();
const roles = ["원장", "부원장", "실장", "디자이너"];
for (const shop of roster.businesses) {
  assert(catalogKeys.has(shop.source_key), `Unknown shop: ${shop.source_key}`);
  assert(!seen.has(shop.source_key), `Duplicate shop: ${shop.source_key}`);
  seen.add(shop.source_key);
  assert.equal(shop.name, catalog.businesses.find(item => item.source_key === shop.source_key).name);
  assert(shop.staff.length >= 4 && shop.staff.length <= 8, `${shop.name}: expected 4–8 staff`);
  assert.equal(new Set(shop.staff.map(person => person.name)).size, shop.staff.length, `${shop.name}: duplicate names`);
  assert(shop.staff.every(person => typeof person.name === "string" && person.name.trim() === person.name && person.name.length > 0 && roles.includes(person.position)));
  const count = role => shop.staff.filter(person => person.position === role).length;
  assert.equal(count("원장"), 1, `${shop.name}: expected one director`);
  assert.equal(count("부원장"), 1, `${shop.name}: expected one deputy director`);
  assert(count("실장") < count("디자이너"), `${shop.name}: managers must be fewer than designers`);
  assert(shop.staff.every((person, index) => index === 0 || roles.indexOf(shop.staff[index - 1].position) <= roles.indexOf(person.position)), `${shop.name}: role order`);
}
assert.deepEqual(seen, catalogKeys, "Every supplied shop needs a roster");

// Compact grouped payload: [stable shop key, [director, deputy, ...], manager count].
// The last names are designers. Four-person shops deliberately have no manager.
const payload = roster.businesses.map(shop => [shop.source_key, shop.staff.map(person => person.name), shop.staff.filter(person => person.position === "실장").length]);
const sql = `-- Generated by node scripts/prepare-provided-staff.mjs. Do not edit by hand.
-- Invented names/assignments authorized by the user, not real employee information.
-- Adds staff only. Does not change schema, permissions, bookings, or working hours.
begin;
do $provided_staff$
declare
  roster jsonb := $staff_json$${JSON.stringify(payload)}$staff_json$::jsonb;
  shop jsonb;
  person record;
  bid bigint;
  role_name text;
begin
  perform pg_advisory_xact_lock(hashtextextended('dealvue:provided-staff:v1', 0));
  for shop in select value from jsonb_array_elements(roster) loop
    select id into strict bid from public.businesses where source_key = shop->>0 for update;
    -- Refuse to overwrite or silently mix with a separately maintained team.
    if exists (
      select 1 from public.staff s where s.business_id = bid
      and not exists (select 1 from jsonb_array_elements_text(shop->1) n where n.value = s.name)
    ) or exists (
      select 1 from public.staff s where s.business_id = bid group by s.name having count(*) > 1
    ) then
      raise exception 'Existing staff differ from the prepared roster: %', shop->>0;
    end if;
    for person in select value as name, ordinality as n from jsonb_array_elements_text(shop->1) with ordinality loop
      role_name := case when person.n = 1 then '원장' when person.n = 2 then '부원장'
        when person.n <= 2 + (shop->>2)::integer then '실장' else '디자이너' end;
      if exists (select 1 from public.staff where business_id = bid and name = person.name and position <> role_name) then
        raise exception 'Existing staff role differs: % / %', shop->>0, person.name;
      end if;
      insert into public.staff (business_id, name, position)
      select bid, person.name, role_name
      where not exists (select 1 from public.staff where business_id = bid and name = person.name);
    end loop;
    if (select count(*) from public.staff where business_id = bid) <> jsonb_array_length(shop->1) then
      raise exception 'Staff count mismatch: %', shop->>0;
    end if;
  end loop;
end
$provided_staff$;
select b.source_key, b.name, count(s.id) as staff_count,
  count(*) filter (where s.position = '원장') as directors,
  count(*) filter (where s.position = '부원장') as deputies,
  count(*) filter (where s.position = '실장') as managers,
  count(*) filter (where s.position = '디자이너') as designers
from public.businesses b join public.staff s on s.business_id = b.id
where b.source_key in (${payload.map(shop => `'${shop[0].replaceAll("'", "''")}'`).join(", ")})
group by b.source_key, b.name order by b.source_key;
commit;
`;
const output = new URL("database/seed-provided-staff.sql", root);
const summaryPath = new URL("database/provided-staff-roster.md", root);
const summary = `# 제공 매장 스태프 명단

사용자가 요청한 가상 활동명과 배치다. 실제 매장의 직원 정보가 아니다. 네이버 예약의 [활동명·직급 표기](https://m.booking.naver.com/booking/13/bizes/1201320/items/6052586)와 [살롱의 디자이너 표기](https://www.chop.kr/22)를 참고했다.

매장별 4~8명, 원장·부원장 각 1명이다. 실장은 없어도 되며, 있는 경우 디자이너보다 적다. 다른 매장의 이름 중복은 허용한다.

| 매장 | 인원 | 원장 | 부원장 | 실장 | 디자이너 |
|---|---:|---|---|---|---|
${roster.businesses.map(shop => `| ${shop.name} | ${shop.staff.length} | ${roles.map(role => shop.staff.filter(person => person.position === role).map(person => person.name).join(", ") || "없음").join(" | ")} |`).join("\n")}

총 ${roster.businesses.length}개 매장, ${roster.businesses.reduce((sum, shop) => sum + shop.staff.length, 0)}명.

원본은 src/data/provided-staff.json이다. 수정 후 \`node scripts/prepare-provided-staff.mjs\`로 SQL과 이 명단을 함께 생성한다. \`--check\`로 조건과 생성 결과를 검증할 수 있다.

등록 SQL은 기존 staff 테이블에만 추가하며, 같은 명단으로 재실행해도 중복 생성하지 않는다. 기존 명단·직급이 다르면 덮어쓰지 않고 전체 등록을 중단한다. 스키마·권한·예약·근무 시간은 바꾸지 않는다. 운영 DB 반영 여부는 별도로 확인해야 한다.
`;
if (process.argv.includes("--check")) {
  assert.equal(await readFile(output, "utf8"), sql, "Regenerate the staff SQL after changing the roster");
  assert.equal(await readFile(summaryPath, "utf8"), summary, "Regenerate the roster summary after changing the roster");
} else {
  await mkdir(new URL("database/", root), { recursive: true });
  await writeFile(output, sql);
  await writeFile(summaryPath, summary);
}
console.log(`Validated ${seen.size} shops, ${roster.businesses.reduce((sum, shop) => sum + shop.staff.length, 0)} staff, 4–8 per shop; ${process.argv.includes("--check") ? "SQL is current" : "SQL generated"}.`);
