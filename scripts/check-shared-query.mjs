// Deterministic concurrency/polling checks; no network or production data.
import assert from 'node:assert/strict';
import { mock } from 'node:test';
import { createSharedQuery } from '../src/features/consumer/sharedQuery.ts';

globalThis.window = new EventTarget();
globalThis.document = new EventTarget();
document.visibilityState = 'visible';
mock.timers.enable({ apis: ['setTimeout', 'Date'], now: 1_000_000 });
const random = Math.random;
Math.random = () => 0;
const flush = async () => { for (let i = 0; i < 12; i++) await Promise.resolve(); };
const dispatch = name => window.dispatchEvent(new Event(name));
const visibility = state => { document.visibilityState = state; document.dispatchEvent(new Event('visibilitychange')); };
let calls = 0;
let finish;
const query = createSharedQuery(() => { calls++; return new Promise(resolve => { finish = resolve; }); }, 1000);
const stopA = query.subscribe(() => {});
const stopB = query.subscribe(() => {});
await flush();
assert.equal(calls, 1, 'two consumers share the initial request');
assert.equal(query.getSnapshot().fetching, true, 'pending reads are distinguishable from a missing reservation');
mock.timers.tick(10_000); dispatch('focus'); query.retry(); await flush();
assert.equal(calls, 1, 'slow requests never overlap, including focus and retry');
dispatch('dealvue-bookings-changed'); dispatch('dealvue-bookings-changed'); await flush();
assert.equal(calls, 1);
finish(['old']); await flush();
assert.equal(calls, 2, 'mutations during a pending read coalesce into one fresh read');
finish(['fresh']); await flush();
assert.deepEqual(query.getSnapshot().data, ['fresh']);
assert.equal(query.getSnapshot().fetching, false);
visibility('hidden'); mock.timers.tick(20_000); dispatch('focus'); await flush();
assert.equal(calls, 2, 'hidden tabs do not poll');
visibility('visible'); await flush();
assert.equal(calls, 3, 'returning to a stale tab refreshes');
finish(['visible']); await flush();
stopA(); stopB(); mock.timers.tick(20_000); await flush();
assert.equal(calls, 3, 'last unsubscribe stops polling');
// Inactive cached queries must notice mutations too.
dispatch('dealvue-bookings-changed');
const stopC = query.subscribe(() => {}); await flush();
assert.equal(calls, 4);
finish(['changed']); await flush(); stopC();
console.log('PASS shared requests, slow reads, mutation invalidation, hidden tabs, resume and unsubscribe');

let retries = 0;
let failing = false;
const backoff = createSharedQuery(async () => { retries++; if (failing) throw new Error('offline'); return 7; }, 1000);
const stopD = backoff.subscribe(() => {}); await flush();
failing = true;
mock.timers.tick(1000); await flush(); assert.equal(retries, 2);
assert.equal(backoff.getSnapshot().data, 7, 'temporary failures retain existing data');
mock.timers.tick(1000); await flush(); assert.equal(retries, 2, 'failure backs off');
mock.timers.tick(1000); await flush(); assert.equal(retries, 3);
mock.timers.tick(3999); await flush(); assert.equal(retries, 3);
mock.timers.tick(1); await flush(); assert.equal(retries, 4, 'repeated failure doubles retry delay');
failing = false; backoff.retry(); await flush(); assert.equal(backoff.getSnapshot().error, null);
mock.timers.tick(1000); await flush(); assert.equal(retries, 6, 'successful recovery restores regular interval');
stopD();
Math.random = random;
mock.timers.reset();
console.log('PASS retained data, exponential backoff, explicit retry and recovery');
