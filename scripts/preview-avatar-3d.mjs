// Inspect the closed endpoint of the actual exported blink morph in a fixture.
const source = await readFile("public/models/avatar-prototype/avatar.glb");
const jsonSize = source.readUInt32LE(12);
const model = JSON.parse(source.subarray(20,20+jsonSize).toString());
for (const mesh of model.meshes) if (mesh.extras?.targetNames?.includes("blink")) mesh.weights = [1];
const json = Buffer.from(JSON.stringify(model)), padded = Buffer.alloc(Math.ceil(json.length/4)*4,32);
json.copy(padded);
const binary = source.subarray(20+jsonSize), header = Buffer.alloc(20);
header.writeUInt32LE(0x46546c67,0); header.writeUInt32LE(2,4); header.writeUInt32LE(20+padded.length+binary.length,8); header.writeUInt32LE(padded.length,12); header.writeUInt32LE(0x4e4f534a,16);
const fixture = Buffer.concat([header,padded,binary]);
const blinkPage = await browser.newPage({ viewport: { width: 1100, height: 1100 }, reducedMotion: "reduce" });
await blinkPage.route("**/models/avatar-prototype/avatar.glb", route => route.fulfill({ contentType:"model/gltf-binary", body:fixture }));
await blinkPage.goto((process.env.DEALVUE_TEST_URL ?? "http://127.0.0.1:5180") + "/avatar-3d");
